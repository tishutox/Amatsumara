-- Run in Supabase Dashboard -> SQL Editor.
-- Stores private, per-account notifications shown by the Lumii app.

create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null,
  body text not null default '',
  is_read boolean not null default false,
  created_at timestamptz not null default now(),
  constraint notifications_title_length check (char_length(title) between 1 and 120),
  constraint notifications_body_length check (char_length(body) <= 2000)
);

create table if not exists public.friend_requests (
  id bigint generated by default as identity primary key,
  requester_id uuid not null references public.profiles(id) on delete cascade,
  addressee_id uuid not null references public.profiles(id) on delete cascade,
  status text not null default 'pending',
  created_at timestamptz not null default now(),
  responded_at timestamptz,
  constraint friend_requests_not_self check (requester_id <> addressee_id),
  constraint friend_requests_status check (
    status in ('pending', 'accepted', 'declined')
  )
);

alter table public.friend_requests
drop constraint if exists friend_requests_pair_unique;

create unique index if not exists friend_requests_pending_pair_unique
on public.friend_requests (
  least(requester_id::text, addressee_id::text),
  greatest(requester_id::text, addressee_id::text)
)
where status = 'pending';

create table if not exists public.friendships (
  id bigint generated by default as identity primary key,
  user_a uuid not null references public.profiles(id) on delete cascade,
  user_b uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  constraint friendships_not_self check (user_a <> user_b),
  constraint friendships_pair_unique unique (user_a, user_b)
);

alter table public.notifications
add column if not exists kind text not null default 'general';

alter table public.notifications
add column if not exists actor_id uuid references public.profiles(id) on delete set null;

alter table public.notifications
add column if not exists friend_request_id bigint
references public.friend_requests(id) on delete set null;

alter table public.notifications
add column if not exists action_status text not null default 'none';

create index if not exists friend_requests_participants_idx
on public.friend_requests (requester_id, addressee_id, status);

create index if not exists friendships_users_idx
on public.friendships (user_a, user_b);

create index if not exists notifications_user_created_at_idx
on public.notifications (user_id, created_at desc);

alter table public.notifications enable row level security;
alter table public.friend_requests enable row level security;
alter table public.friendships enable row level security;

drop policy if exists "Participants can read friend requests" on public.friend_requests;
create policy "Participants can read friend requests"
on public.friend_requests for select
to authenticated
using (
  (select auth.uid()) = requester_id
  or (select auth.uid()) = addressee_id
);

drop policy if exists "Friends can read their friendships" on public.friendships;
create policy "Friends can read their friendships"
on public.friendships for select
to authenticated
using (
  (select auth.uid()) = user_a
  or (select auth.uid()) = user_b
);

drop policy if exists "Users can read their notifications" on public.notifications;
create policy "Users can read their notifications"
on public.notifications for select
to authenticated
using ((select auth.uid()) = user_id);

create or replace function public.get_relationship_status(p_target_user_id uuid)
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare
  current_user_id uuid := auth.uid();
begin
  if current_user_id is null then
    return 'signed_out';
  end if;
  if current_user_id = p_target_user_id then
    return 'self';
  end if;
  if exists (
    select 1 from public.friendships
    where (user_a = current_user_id and user_b = p_target_user_id)
       or (user_a = p_target_user_id and user_b = current_user_id)
  ) then
    return 'friends';
  end if;
  if exists (
    select 1 from public.friend_requests
    where requester_id = current_user_id
      and addressee_id = p_target_user_id
      and status = 'pending'
  ) then
    return 'outgoing_pending';
  end if;
  if exists (
    select 1 from public.friend_requests
    where requester_id = p_target_user_id
      and addressee_id = current_user_id
      and status = 'pending'
  ) then
    return 'incoming_pending';
  end if;
  return 'none';
end;
$$;

create or replace function public.send_friend_request(p_target_user_id uuid)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  current_user_id uuid := auth.uid();
  request_id bigint;
  sender_username text;
begin
  if current_user_id is null then
    raise exception 'Sign in to send a friend request.';
  end if;
  if current_user_id = p_target_user_id then
    raise exception 'You cannot send a friend request to yourself.';
  end if;
  if not exists (select 1 from public.profiles where id = p_target_user_id) then
    raise exception 'Profile not found.';
  end if;
  if exists (
    select 1 from public.friendships
    where (user_a = current_user_id and user_b = p_target_user_id)
       or (user_a = p_target_user_id and user_b = current_user_id)
  ) then
    raise exception 'You are already friends.';
  end if;
  if exists (
    select 1 from public.friend_requests
    where requester_id = p_target_user_id
      and addressee_id = current_user_id
      and status = 'pending'
  ) then
    raise exception 'This person has already sent you a friend request.';
  end if;

  insert into public.friend_requests (
    requester_id, addressee_id, status, created_at, responded_at
  ) values (
    current_user_id, p_target_user_id, 'pending', now(), null
  )
  returning id into request_id;

  select username into sender_username
  from public.profiles where id = current_user_id;

  insert into public.notifications (
    user_id, actor_id, friend_request_id, kind, action_status,
    title, body
  ) values (
    p_target_user_id, current_user_id, request_id, 'friend_request', 'pending',
    'Friend request', '@' || sender_username || ' sent you a friend request.'
  );

  return request_id;
end;
$$;

create or replace function public.respond_to_friend_request(
  p_request_id bigint,
  p_response text
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  current_user_id uuid := auth.uid();
  request_row public.friend_requests%rowtype;
  requester_username text;
  addressee_username text;
  first_user uuid;
  second_user uuid;
begin
  if p_response not in ('accepted', 'declined') then
    raise exception 'Invalid friend request response.';
  end if;

  select * into request_row
  from public.friend_requests
  where id = p_request_id
  for update;

  if request_row.id is null or request_row.addressee_id <> current_user_id then
    raise exception 'Friend request not found.';
  end if;
  if request_row.status <> 'pending' then
    raise exception 'This friend request was already answered.';
  end if;

  update public.friend_requests
  set status = p_response, responded_at = now()
  where id = p_request_id;

  update public.notifications
  set action_status = p_response
  where friend_request_id = p_request_id
    and user_id = current_user_id
    and kind = 'friend_request';

  if p_response = 'accepted' then
    if request_row.requester_id::text < request_row.addressee_id::text then
      first_user := request_row.requester_id;
      second_user := request_row.addressee_id;
    else
      first_user := request_row.addressee_id;
      second_user := request_row.requester_id;
    end if;

    insert into public.friendships (user_a, user_b)
    values (first_user, second_user)
    on conflict (user_a, user_b) do nothing;

    select username into requester_username
    from public.profiles where id = request_row.requester_id;
    select username into addressee_username
    from public.profiles where id = request_row.addressee_id;

    insert into public.notifications (
      user_id, actor_id, kind, action_status, title, body
    ) values
    (
      request_row.requester_id,
      request_row.addressee_id,
      'friendship',
      'none',
      'You are now friends',
      '@' || addressee_username || ' accepted your friend request.'
    ),
    (
      request_row.addressee_id,
      request_row.requester_id,
      'friendship',
      'none',
      'You are now friends',
      'You and @' || requester_username || ' are now friends.'
    );
  end if;
end;
$$;

create or replace function public.unfriend_user(p_target_user_id uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  current_user_id uuid := auth.uid();
begin
  if current_user_id is null then
    raise exception 'Sign in to unfriend someone.';
  end if;
  delete from public.friendships
  where (user_a = current_user_id and user_b = p_target_user_id)
     or (user_a = p_target_user_id and user_b = current_user_id);
end;
$$;

revoke all on function public.get_relationship_status(uuid) from public;
revoke all on function public.send_friend_request(uuid) from public;
revoke all on function public.respond_to_friend_request(bigint, text) from public;
revoke all on function public.unfriend_user(uuid) from public;

grant execute on function public.get_relationship_status(uuid) to authenticated;
grant execute on function public.send_friend_request(uuid) to authenticated;
grant execute on function public.respond_to_friend_request(bigint, text) to authenticated;
grant execute on function public.unfriend_user(uuid) to authenticated;

drop policy if exists "Users can update their notifications" on public.notifications;
create policy "Users can update their notifications"
on public.notifications for update
to authenticated
using ((select auth.uid()) = user_id)
with check ((select auth.uid()) = user_id);

drop policy if exists "Users can delete their notifications" on public.notifications;
create policy "Users can delete their notifications"
on public.notifications for delete
to authenticated
using ((select auth.uid()) = user_id);
